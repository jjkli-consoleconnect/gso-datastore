SELECT
  Incident_Number,
  Status,
  CaseType,
  NOC,
  Categorization_Tier_1,
  Categorization_Tier_2,
  Categorization_Tier_3,
  GCSC_1st_Customer_Update,
  GCSC_2nd_Customer_Update,
  GCSC_3rd_Customer_Update,
  Initial_Response_Time,
  Second_Response_Time,
  Third_Response_Time,
  Prod_ID,
  Fault_Cause,
  Closed_Date,
  Submit_Date,
  Assignee,
  Closed_By,
  Submitter,
  TrueMTTR_mins,
  Cust_ID,
  Carrier,
  Customer_Name,
  SRno,
  LastResolvedDate,
  ReportedDate,
  RespondedDate,
  FaultCauseDetail,
  LastModifiedDate,
  ReportedBy,
  Product_Family,
  ProductDescription,
  GSMP_Circuit_ID,
  NULL AS Work_Log_Type,
  NULL AS WorkLog_ID,
  NULL AS WorkLog_Submit_Date,
  NULL AS Work_Log_Submitter,
  NULL AS WorkLog_Last_Modified_Date,
  NULL AS WorkLog_Last_Modified_By,
  NULL AS ExtractedDescription,
  NULL AS inserted_at,
  Shift,
  Date,
  DoW,
  NULLIF(TRIM(Submitter), '') AS Creation_FullName,
  NULL AS Closure_FullName,
  'Creation' AS Event_Type
FROM (
  SELECT
    hd.Incident_Number,
    hd.Status,
    hd.CaseType,
    hd.Assigned_Group AS NOC,
    hd.Categorization_Tier_1,
    hd.Categorization_Tier_2,
    hd.Categorization_Tier_3,
    hd.GCSC_1st_Customer_Update,
    hd.GCSC_2nd_Customer_Update,
    hd.GCSC_3rd_Customer_Update,
    hd.Initial_Response_Time,
    hd.Second_Response_Time,
    hd.Third_Response_Time,
    hd.Prod_ID,
    hd.Fault_Cause,
    hd.Closed_Date,
    hd.Submit_Date,
    hd.Assignee,
    hd.Closed_By,
    hd.Submitter,
    hd.TrueMTTR_mins,
    hd.Cust_ID,
    hd.Carrier,
    hd.Customer_Name,
    hd.SRno,
    hd.LastResolvedDate,
    hd.ReportedDate,
    hd.RespondedDate,
    hd.FaultCauseDetail,
    hd.LastModifiedDate,
    hd.ReportedBy,
    hd.Product_Family,
    hd.ProductDescription,
    hd.GSMP_Circuit_ID,
    CASE
      WHEN EXTRACT(HOUR FROM hd.Submit_Date) BETWEEN 0 AND 5 THEN FORMAT_TIMESTAMP('%Y-%m-%d', DATE_SUB(hd.Submit_Date, INTERVAL 1 DAY)) || ' - 3 Evening'
      WHEN EXTRACT(HOUR FROM hd.Submit_Date) BETWEEN 6 AND 13 THEN FORMAT_TIMESTAMP('%Y-%m-%d', hd.Submit_Date) || ' - 1 Morning'
      WHEN EXTRACT(HOUR FROM hd.Submit_Date) BETWEEN 14 AND 21 THEN FORMAT_TIMESTAMP('%Y-%m-%d', hd.Submit_Date) || ' - 2 Afternoon'
      ELSE FORMAT_TIMESTAMP('%Y-%m-%d', hd.Submit_Date) || ' - 3 Evening'
    END AS Shift,
    hd.Submit_Date AS Date,
    CASE
      WHEN EXTRACT(HOUR FROM hd.Submit_Date) BETWEEN 0 AND 5 THEN FORMAT_TIMESTAMP('%a', DATE_SUB(hd.Submit_Date, INTERVAL 1 DAY))
      ELSE FORMAT_TIMESTAMP('%a', hd.Submit_Date)
    END AS DoW
  FROM `pccw-internal-virt-agent-uat.GSO.HelpDeskAllNOC` AS hd
  WHERE hd.Assigned_Group != 'Quality Assurance' AND hd.Status != 'Cancelled'
) AS creation

UNION ALL

